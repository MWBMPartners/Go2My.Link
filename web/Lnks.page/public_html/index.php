// ============================================================================
// 🧯 Step 3b: Apache ErrorDocument Dispatch (#114)
// ============================================================================
// Some errors (e.g. a Require-denied 403 on a blocked directory such as
// .auth/, or a PHP fatal 500 with no output) are generated by Apache itself
// and never reach the slug resolver below — no request runs through this
// file first. The ErrorDocument directives in .htaccess route those straight
// back here via ?http_error=, so G2ML_COMPONENT and page_init.php (above) are
// already in place before the branded pages' Direct Access Guard runs.
// Whitelisted to a fixed set of codes only; anything else (including normal
// ?slug= requests) falls straight through to Step 4 below untouched.
// ============================================================================

$httpErrorCode = $_GET['http_error'] ?? '';

if ($httpErrorCode === '403' || $httpErrorCode === '404' || $httpErrorCode === '500')
{
    if ($httpErrorCode === '403')
    {
        http_response_code(403);
        require __DIR__ . DIRECTORY_SEPARATOR . '403.php';
    }
    elseif ($httpErrorCode === '500')
    {
        http_response_code(500);
        require __DIR__ . DIRECTORY_SEPARATOR . '500.php';
    }
    else
    {
        http_response_code(404);
        require __DIR__ . DIRECTORY_SEPARATOR . '404.php';
    }

    exit;
}

